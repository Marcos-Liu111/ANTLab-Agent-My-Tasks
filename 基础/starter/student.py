"""student.py — 文档阅读与信息核验的证据组织实现。

设计说明（prompt 设计依据，见 decisions.md）：
1. 四元组精确匹配：题目要求按 项目/版本/月份/批次/指标口径 精确核对，
   prompt 中显式列出这些字段，要求模型逐字段比对而非关键词相似度。
2. 跨段计算开放：基础题存在分子分母分处两段的情况（如 D01 的 68/85），
   因此允许多段组合，但引用必须逐一列出被使用的段落ID。
3. 证据不足优先：字段对不上时返回"证据不足"，禁止用相近批次/月份的数据顶替，
   这是防止编造的核心约束。
4. 输出契约固定：严格 JSON {"answer","citations"}，便于 runner 解析与复算。

--- v2 改进（A+B 组合，冻结后启用，见 decisions.md 决策3） ---
A 层 improve()：证据分层重排。依据 T08/R0 失败分析——陷阱段（迁移批次）
  位于输入序列第2位时引发误判，规则页/主记录页被推到第6~7位。
  重排为：规则页(1档) → 主记录页(2档) → 其他(3档) → 旁证陷阱页(4档)。
  仅重排顺序，不修改 id/source/text，不读题号/答案标签。
B 层 system prompt 追加"批次冲突处理"：批次不符的段落应显式排除，
  不得当作证据冲突回退拒答——对应 T08/R0 把相近记录当成冲突而答"证据不足"。
"""

SYSTEM_PROMPT = """你是一个文档核验助手。你的任务是从给定的资料段落中找到能精确回答问题的证据。

## 匹配规则（必须逐字段核对，不能只看关键词相似）

问题中通常包含这些定位字段，必须在段落中全部精确匹配后才能作为证据：
- 项目名称（如：澄石项目 vs 岫光项目）
- 版本号（如：R3 vs R4）
- 月份/时间窗口（如：2026-03 vs 2026-02）
- 批次类型与代号（如：正式回归批次CS41 vs 迁移批次XQ50 vs 探索组 vs 压力组）
- 指标口径（如：分母是有效问题数还是返回成功数；分子是完整支持还是含部分支持）

任何一个字段不匹配，该段落就不能作为答案依据（即使数字很接近）。
字段匹配看的是记录指向的对象（项目/版本/时间/批次/统计口径），
指标名称措辞不同（如“核验率”“支持率”）时按其定义的分子分母判断，不因措辞不同而拒答。

## 批次冲突处理（重要）

资料中常出现"迁移批次/压力组/探索组/邻项目/邻版本"的相近记录。当它们与
问题指定的批次类型冲突时：
1. 先按批次类型显式排除（不要让相近记录参与证据权衡）；
2. 排除后若主记录与规则页足以作答，正常作答；
3. 只有当排除批次不符的段落后仍无匹配记录时，才回答"证据不足"；
   不要因为存在措辞相近但批次不符的段落就判定为"证据冲突"而拒答。

## 回答规则

1. 只依据给定段落作答，禁止使用外部知识或凭空推断。
2. 可以跨段落组合证据（例如分子在一段、分母在另一段），此时每一段都要列入引用。
3. 需要计算时，先在心里明确分子分母来自哪个段落，再给出结果。
4. 如果所有段落中都找不到字段完全匹配的记录，回答"证据不足"，
   并把最接近但不满足条件的段落ID列入 citations（表示你检查过这些来源）。
5. 答案要简短：按题目要求的格式输出（百分数、数值、简短词组等）。
6. 引用的每个段落ID必须真实出现在本次输入中，禁止编造ID。

## 输出格式

只输出一个JSON对象，不要输出任何其他文字，不要使用markdown代码围栏（```）：

{"answer": "简短答案", "citations": ["段落ID1", "段落ID2"]}

注意：
- answer 是字符串
- citations 是字符串数组，即使只有一个证据也要用数组
- 证据不足时 answer 为 "证据不足"
"""


def prepare_messages(question, passages):
    """返回 [{"role":"system|user", "content":"..."}, ...]。

    passages仅含id/source/text，不包含答案或条件标记。
    必须请求JSON对象: {"answer": "简短答案", "citations": ["P..."]}。
    """
    lines = []
    for i, p in enumerate(passages, 1):
        # 保留原始 id/source/text，不做任何重映射
        lines.append(f"[段落{i}] ID: {p['id']} | 来源: {p['source']}\n{p['text']}")

    user_content = (
        f"## 问题\n{question}\n\n"
        f"## 资料段落（共{len(passages)}段）\n\n"
        + "\n\n".join(lines)
        + "\n\n请根据以上段落回答问题，严格输出JSON。"
    )

    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user_content},
    ]


def improve(question, passages):
    """A 层：证据分层重排（仅重排，不改内容）。

    分档规则（只用段落自身的 text/source 特征，不使用题号、条件或答案标签）：
      档0 复核补页/规则页：判定规则所在，最先呈现
      档1 主记录页：含"的记录："且非旁证批次的项目主记录
      档2 其他未分类段落
      档3 旁证/陷阱页：迁移批次、压力组、探索组、邻项目(岫光)、邻版本(R3/R4反向)
    使用稳定排序（sorted），同档内保持原顺序。
    """
    def tier(p):
        t = p.get("text", "")
        head = t[:80]
        if "复核补页" in t or "规则" in head:
            return 0
        if "的记录：" in t and not any(
            k in t for k in ("迁移批次", "压力组", "探索组")
        ):
            return 1
        if any(k in t for k in ("迁移批次", "压力组", "探索组", "岫光")):
            return 3
        return 2

    return sorted(passages, key=tier)
